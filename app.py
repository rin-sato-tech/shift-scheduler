from __future__ import annotations

import streamlit as st

from src.db import init_db


init_db()

st.set_page_config(
    page_title="シフト自動作成デモ",
    page_icon="📅",
    layout="wide",
)

st.title("シフト自動作成デモ")

st.write(
    "従業員情報、希望休、必要人数をもとに、"
    "月間シフトを自動生成するデモアプリです。"
)

st.info("左側のメニューから、次の順番で操作してください。")

st.subheader("操作の流れ")

st.markdown(
    """
1. **従業員管理**  
    従業員、責任者区分、契約勤務日数、勤務可能シフトを登録します。

2. **希望休入力**  
    対象月ごとの希望休を登録します。

3. **必要人数設定**  
    日付・シフトごとの必要人数と必要責任者数を設定します。

4. **シフト生成**  
    入力条件を検証し、月間シフトを自動生成します。

5. **シフト手動変更**  
    生成結果を必要に応じて調整します。

6. **CSV出力**  
    月間表、配置明細、勤務集計をダウンロードします。
"""
)

st.subheader("主な制約")

st.markdown(
    """
- 1人につき1日1シフト
- 希望休には配置しない
- 勤務可能シフトだけに配置
- 必要人数を満たす
- 必要責任者数を満たす
- 契約勤務日数との差を抑える
- 連続勤務日数を制限する
"""
)
